create table if not exists public.contacts (
  id bigint generated by default as identity primary key,
  nome text not null,
  telefone text not null,
  created_at timestamptz not null default now()
);

comment on table public.contacts is
  'Contatos autorizados para o MVP técnico.';

comment on column public.contacts.nome is
  'Nome usado para personalizar a mensagem.';

comment on column public.contacts.telefone is
  'Telefone em formato internacional, somente dígitos. Use apenas dados fictícios, próprios ou autorizados.';

-- Tabelas criadas pelo SQL Editor precisam de RLS habilitado manualmente.
-- Sem políticas públicas, somente uma chave secreta de backend/service role
-- deve acessar os contatos usados pelo worker local.
alter table public.contacts enable row level security;

revoke all privileges on table public.contacts
  from anon, authenticated;

revoke all privileges on sequence public.contacts_id_seq
  from anon, authenticated;

-- Registro de entregas. Existe por um motivo específico: sem esta tabela, rodar
-- o worker duas vezes manda a mesma mensagem de novo para o mesmo contato.
-- A chave primária em `phone` é o que impede a duplicata.
create table if not exists public.deliveries (
  phone text primary key,
  status text not null default 'sent' check (status in ('sent', 'failed')),
  attempts integer not null default 1,
  sent_at timestamptz not null default now()
);

comment on table public.deliveries is
  'Controle de reenvio do worker. Uma linha por telefone já atendido.';

alter table public.deliveries enable row level security;

revoke all privileges on table public.deliveries
  from anon, authenticated;

